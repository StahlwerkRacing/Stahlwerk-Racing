function getGT7Manufacturers() {
    return [...new Set(
        GT7_CARS.map(car => car.manufacturer)
    )].sort((a, b) => a.localeCompare(b, "de"));
}


function searchGT7Cars(searchTerm) {

    const term = searchTerm
        .toLowerCase()
        .trim();

    if (!term) {
        return GT7_CARS;
    }

    return GT7_CARS.filter(car => {

        const manufacturer =
            car.manufacturer.toLowerCase();

        const name =
            car.name.toLowerCase();

        return (
            manufacturer.includes(term) ||
            name.includes(term)
        );

    });

}


function getGT7CarsByManufacturer(manufacturer) {

    return GT7_CARS.filter(
        car =>
            car.manufacturer.toLowerCase() ===
            manufacturer.toLowerCase()
    );

}


function getGT7PowerPackCars() {

    return GT7_CARS.filter(
        car => car.powerPack === true
    );

}


function getGT7SpecialEditions() {

    return GT7_CARS.filter(
        car => car.specialEdition === true
    );

}
